class FlowmatchingActionHead(nn.Module):
    def __init__(
        self,
        full_config,
    ):
        super().__init__()
        config = full_config.framework.action_model
        self.hidden_size = config.hidden_size # @JinhuiYE
        self.full_config = full_config
        action_model_type = config.action_model_type
        action_model_cfg = DiTConfig[action_model_type]
        
        self.input_embedding_dim = action_model_cfg["input_embedding_dim"]
        diffusion_model_cfg = config.diffusion_model_cfg
        diffusion_model_cfg = {**action_model_cfg, **diffusion_model_cfg}
        self.model = DiT(**diffusion_model_cfg)
        self.action_dim = config.action_dim
        self.action_horizon = config.future_action_window_size + 1
        self.num_inference_timesteps = config.num_inference_timesteps

        self.state_encoder = MLP(
            input_dim=config.state_dim,
            hidden_dim=self.hidden_size,
            output_dim=self.input_embedding_dim,
        ) if config.state_dim else None

        self.action_encoder = ActionEncoder(
            action_dim=config.action_dim,
            hidden_size=self.input_embedding_dim,
        )
        self.action_decoder = MLP(
            input_dim=self.model.config.output_dim,
            hidden_dim=self.hidden_size,
            output_dim=self.action_dim,
        )
        self.future_tokens = nn.Embedding(config.num_target_vision_tokens, self.input_embedding_dim)
        nn.init.normal_(self.future_tokens.weight, mean=0.0, std=0.02)

        if config.add_pos_embed:
            self.position_embedding = nn.Embedding(config.max_seq_len, self.input_embedding_dim)
            nn.init.normal_(self.position_embedding.weight, mean=0.0, std=0.02)

        self.beta_dist = Beta(config.noise_beta_alpha, config.noise_beta_beta)
        self.num_timestep_buckets = config.num_timestep_buckets
        self.config = config

    def sample_time(self, batch_size, device, dtype):
        sample = self.beta_dist.sample([batch_size]).to(device, dtype=dtype).clamp(max=self.config.noise_s)
        return (self.config.noise_s - sample) / self.config.noise_s

    def prepare_input(self, batch: dict) -> BatchFeature:
        return BatchFeature(data=batch)


    def forward(self, vl_embs: torch.Tensor, actions: torch.Tensor, state: torch.Tensor = None, encoder_attention_mask=None):
        """
        vl_embs: shape (B, seq_length, feature_dim)
        actions: shape (B, future_action_window_size, D_action)
        """
        device = vl_embs.device

        # Embed noised action trajectory.
        noise = torch.randn(actions.shape, device=actions.device, dtype=actions.dtype)
        t = self.sample_time(actions.shape[0], device=actions.device, dtype=actions.dtype)
        t = t[:, None, None]  # shape (B,1,1) for broadcast

        noisy_trajectory = (1 - t) * noise + t * actions
        velocity = actions - noise

        # Convert (continuous) t -> discrete if needed
        t_discretized = (t[:, 0, 0] * self.num_timestep_buckets).long()
        action_features = self.action_encoder(noisy_trajectory, t_discretized)


        # embed state
        state_features = self.state_encoder(state) if state is not None else None


        # Maybe add position embedding.
        if self.config.add_pos_embed:
            pos_ids = torch.arange(action_features.shape[1], dtype=torch.long, device=device)
            pos_embs = self.position_embedding(pos_ids).unsqueeze(0)
            action_features = action_features + pos_embs

        # state and action embedding along sequence dimension.
        future_tokens = self.future_tokens.weight.unsqueeze(0).expand(vl_embs.shape[0], -1, -1)
        sa_embs = torch.cat((state_features, future_tokens, action_features), dim=1) \
            if state_features is not None else torch.cat((future_tokens, action_features), dim=1)

        # Join VLM features with state and action embedding along sequence dimension.
        model_output = self.model(
            hidden_states=sa_embs,
            encoder_hidden_states=vl_embs,
            encoder_attention_mask=encoder_attention_mask,
            timestep=t_discretized,
            return_all_hidden_states=False,  # NOTE (YL): not using flare now
        )
        pred = self.action_decoder(model_output)
        pred_actions = pred[:, -actions.shape[1] :]

        # Slice out only the action portion of pred and target.
        loss = ((pred_actions - velocity) ** 2).mean()
        return loss

    def _predict_velocity(
        self,
        actions: torch.Tensor,
        vl_embs: torch.Tensor,
        state_features: torch.Tensor = None,
        t_cont: float = 0.0,
    ) -> torch.Tensor:
        batch_size = actions.shape[0]
        device = actions.device
        t_discretized = int(t_cont * self.num_timestep_buckets)
        timesteps_tensor = torch.full(
            size=(batch_size,),
            fill_value=t_discretized,
            dtype=torch.long,
            device=device,
        )

        action_features = self.action_encoder(actions, timesteps_tensor)
        if self.config.add_pos_embed:
            pos_ids = torch.arange(action_features.shape[1], dtype=torch.long, device=device)
            pos_embs = self.position_embedding(pos_ids).unsqueeze(0)
            action_features = action_features + pos_embs

        future_tokens = self.future_tokens.weight.unsqueeze(0).expand(vl_embs.shape[0], -1, -1)
        sa_embs = torch.cat((state_features, future_tokens, action_features), dim=1) \
            if state_features is not None else torch.cat((future_tokens, action_features), dim=1)

        model_output = self.model(
            hidden_states=sa_embs,
            encoder_hidden_states=vl_embs,
            timestep=timesteps_tensor,
        )
        pred = self.action_decoder(model_output)
        return pred[:, -actions.shape[1] :]

    @torch.no_grad()
    def predict_action(self, vl_embs: torch.Tensor, state: torch.Tensor = None) -> torch.Tensor:
        # Set initial actions as the sampled noise.
        batch_size = vl_embs.shape[0]
        device = vl_embs.device
        actions = torch.randn( # yes, here make sure action_horizon align with data loader? or share from clinet?
            size=(batch_size, self.config.action_horizon, self.config.action_dim),
            dtype=vl_embs.dtype,
            device=device,
        )

        num_steps = self.num_inference_timesteps
        dt = 1.0 / num_steps
        
        state_features = self.state_encoder(state) if state is not None else None

        # Run denoising steps.
        for t in range(num_steps):
            t_cont = t / float(num_steps)  # e.g. goes 0, 1/N, 2/N, ...
            pred_velocity = self._predict_velocity(actions, vl_embs, state_features, t_cont)

            # Update actions using euler integration.
            actions = actions + dt * pred_velocity
        return actions

    def predict_action_rtc(
        self,
        vl_embs: torch.Tensor,
        state: torch.Tensor = None,
        *,
        prev_chunk_left_over=None,
        inference_delay: int = 0,
        execution_horizon: int = 8,
        prefix_attention_schedule: str = "exp",
        max_guidance_weight: float = 5.0,
        gripper_indices: tuple[int, ...] | None = (6, 13),
        gripper_guidance_scale: float = 0.0,
    ) -> torch.Tensor:
        """
        Return normalized action chunk [B,H,D].
        If prev_chunk_left_over is None, fallback to ordinary predict_action().
        """
        self._last_rtc_metadata = {
            "applied": False,
            "leftover_len": None,
            "inference_delay": int(inference_delay),
            "execution_horizon": int(execution_horizon),
            "prefix_attention_schedule": prefix_attention_schedule,
        }
        if prev_chunk_left_over is None:
            return self.predict_action(vl_embs, state)

        batch_size = vl_embs.shape[0]
        device = vl_embs.device
        horizon = int(self.config.action_horizon)
        action_dim = int(self.config.action_dim)
        dtype = vl_embs.dtype

        prev_padded, leftover_len = pad_leftover_chunk(
            prev_chunk_left_over,
            batch_size=batch_size,
            horizon=horizon,
            action_dim=action_dim,
            device=device,
            dtype=dtype,
        )
        self._last_rtc_metadata["leftover_len"] = leftover_len
        if leftover_len == 0:
            return self.predict_action(vl_embs, state)

        weights = get_prefix_weights_torch(
            inference_delay=inference_delay,
            execution_horizon=execution_horizon,
            chunk_size=horizon,
            schedule=prefix_attention_schedule,
            device=device,
            dtype=dtype,
        )
        action_mask = make_rtc_action_mask(
            horizon=horizon,
            action_dim=action_dim,
            weights=weights,
            leftover_len=leftover_len,
            gripper_indices=gripper_indices,
            gripper_scale=gripper_guidance_scale,
        )
        if not bool(torch.any(action_mask).item()):
            return self.predict_action(vl_embs, state)

        vl_embs = vl_embs.detach()
        state = state.detach() if state is not None else None
        with torch.no_grad():
            state_features = self.state_encoder(state) if state is not None else None
            if state_features is not None:
                state_features = state_features.detach()

        actions = torch.randn(
            size=(batch_size, horizon, action_dim),
            dtype=dtype,
            device=device,
        )

        num_steps = self.num_inference_timesteps
        dt = 1.0 / num_steps

        for step_idx in range(num_steps):
            t_cont = step_idx / float(num_steps)
            actions = actions.detach().requires_grad_(True)

            pred_velocity = self._predict_velocity(actions, vl_embs, state_features, t_cont)
            x1_hat = actions + (1.0 - t_cont) * pred_velocity
            error = (prev_padded - x1_hat) * action_mask
            scalar = (x1_hat * error.detach()).sum()
            pinv_correction = torch.autograd.grad(
                scalar,
                actions,
                retain_graph=False,
                create_graph=False,
                allow_unused=False,
            )[0]

            guidance_weight = compute_rtc_guidance_weight(t_cont, max_guidance_weight)
            corrected_velocity = pred_velocity + guidance_weight * pinv_correction

            with torch.no_grad():
                actions = actions + dt * corrected_velocity

        self._last_rtc_metadata["applied"] = True
        return actions.detach()

    @property
    def device(self):
        return next(iter(self.parameters())).device

    @property
    def dtype(self):
        return next(iter(self.parameters())).dtype



def get_action_model(config=None):
    """
    Factory: build FlowmatchingActionHead from global framework config.
    
    Args:
        config: Global config (expects config.framework.action_model namespace).

    Returns:
        FlowmatchingActionHead: Initialized FlowMatchingActionHead.
    """
    return FlowmatchingActionHead(
        full_config=config
    )


